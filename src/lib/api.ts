export async function verifyDashboardAccess(userId: string): Promise<boolean> {
  if (!isSupabaseConfigured) return true;
  try {
    const { data, error } = await supabase
      .from('profiles')
      .select('dashboard_access, role')
      .eq('id', userId)
      .single();

    if (!error && data) {
      return Boolean(data.dashboard_access);
    }

    const { data: { session } } = await supabase.auth.getSession();
    if (session?.user) {
      const metaAccess = session.user.app_metadata?.dashboard_access ?? session.user.user_metadata?.dashboard_access;
      if (metaAccess !== undefined) {
        return Boolean(metaAccess);
      }
    }
    return true;
  } catch (e) {
    console.warn('Dashboard access verification check error:', e);
    return true;
  }
}

export interface TelegramAuthPayload {
  id: number;
  first_name: string;
  last_name?: string;
  username?: string;
  photo_url?: string;
  auth_date: number;
  hash: string;
}

export async function loginWithTelegram(telegramPayload: TelegramAuthPayload): Promise<{ magic_link: string; email: string }> {
  const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
  if (!supabaseUrl) throw new Error('Supabase URL not configured');

  const functionUrl = `${supabaseUrl}/functions/v1/telegram-auth`;
  const anonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

  const response = await fetch(functionUrl, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'apikey': anonKey,
      'Authorization': `Bearer ${anonKey}`,
    },
    body: JSON.stringify({ telegramPayload }),
  });

  const result = await response.json();
  if (!response.ok) {
    throw new Error(result.error || 'Telegram authentication failed');
  }
  return result;
}

export async function getTelegramNotifications(): Promise<TelegramNotificationRecord[]> {
  if (isSupabaseConfigured) {
    try {
      const { data, error } = await supabase
        .from('telegram_notifications')
        .select('*')
        .order('timestamp', { ascending: false });
      if (!error && data && data.length > 0) {
        return data as TelegramNotificationRecord[];
      }
    } catch (e) {
      console.warn('Supabase telegram_notifications fetch failed, using local:', e);
    }
  }
  return localNotifications;
}

export async function sendTelegramNotification(
  recipient: string, 
  message: string, 
  channelType: 'admin_private' | 'member_group' = 'admin_private'
): Promise<TelegramNotificationRecord> {
  const newNotif: TelegramNotificationRecord = {
    id: `NOTIF-${Math.floor(100 + Math.random() * 900)}`,
    timestamp: new Date().toISOString().replace('T', ' ').substring(0, 19),
    recipient,
    message,
    channelType,
    status: 'Pending'
  };

  localNotifications = [newNotif, ...localNotifications];

  if (isSupabaseConfigured) {
    try {
      await supabase.from('telegram_notifications').insert([newNotif]);
    } catch (e) {
      console.warn('Supabase insert notification error:', e);
    }
  }

  setTimeout(async () => {
    newNotif.status = 'Sent';
    if (isSupabaseConfigured) {
      try {
        await supabase
          .from('telegram_notifications')
          .update({ status: 'Sent' })
          .eq('id', newNotif.id);
      } catch (e) {
        // ignore
      }
    }
  }, 1000);

  return newNotif;
}

