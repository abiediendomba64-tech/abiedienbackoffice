/**
 * Link Telegram account with verified Supabase session
 */
export async function linkTelegramAccount(telegramId: string | number, email: string, displayName?: string): Promise<{ success: boolean; user?: any }> {
  const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
  if (!supabaseUrl) return { success: true };

  const functionUrl = `${supabaseUrl}/functions/v1/telegram-auth`;
  const anonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

  try {
    const res = await fetch(functionUrl, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'apikey': anonKey,
        'Authorization': `Bearer ${anonKey}`,
      },
      body: JSON.stringify({
        action: 'link_telegram',
        telegram_id: String(telegramId),
        email,
        display_name: displayName
      })
    });
    return await res.json();
  } catch (err) {
    console.warn('linkTelegramAccount request note:', err);
    return { success: false };
  }
}

/**
 * Fetch Claims for User or Admin
 */
export async function fetchUserClaims(telegramId?: string | number): Promise<any[]> {
  if (isSupabaseConfigured) {
    try {
      let query = supabase.from('claims').select('*').order('created_at', { ascending: false });
      if (telegramId) {
        query = query.eq('telegram_user_id', Number(telegramId));
      }
      const { data, error } = await query;
      if (!error && data) return data;
    } catch (e) {
      console.warn('Supabase fetch claims note:', e);
    }
  }
  return [];
}
